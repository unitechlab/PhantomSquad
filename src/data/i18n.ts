const DICTIONARIES: Record<Lang, Record<TextKey, string>> = { en: EN, ja: JA };

export type TextParams = Record<string, string | number>;

/** Looks up a key and fills {placeholders}. When params.n is 1 and "<key>_one" exists, that singular form is used. */
export function translate(lang: Lang, key: TextKey, params?: TextParams): string {
  const dict = DICTIONARIES[lang];
  const singular = `${key}_one` as TextKey;
  const template = params?.n === 1 && singular in dict ? dict[singular] : dict[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

/** Placeholder names used by a template. Exposed for tests that compare English and Japanese. */
export function placeholders(template: string): string[] {
  return Array.from(template.matchAll(/\{(\w+)\}/g), (m) => m[1]).sort();
}

export function textKeys(): TextKey[] {
  return Object.keys(EN) as TextKey[];
}

export function textFor(lang: Lang, key: TextKey): string {
  return DICTIONARIES[lang][key];
}

export function isLang(value: unknown): value is Lang {
  return value === 'en' || value === 'ja';
}
